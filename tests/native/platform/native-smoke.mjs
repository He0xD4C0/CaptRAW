import { EngineClient } from '../../support/engine-client.mjs';
import { resolve } from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
const file = resolve(process.argv[2] || 'build/samples/synthetic.dng');
mkdirSync('artifacts', { recursive: true });
const engine = new EngineClient();
engine.on('error', m => console.error('ENGINE:', m));
await engine.ready;
const start = performance.now();
const image = await engine.call('open', { path: file, sessionId: 'smoke' });
console.log('OPEN', JSON.stringify(image).slice(0, 500));
const pending = engine.preview(1);
const recipe = await engine.call('update', { revision: 1, adjustments: image.adjustments });
const frame = await pending;
console.log('PREVIEW', frame, 'totalMs', performance.now() - start);
writeFileSync('artifacts/smoke.arp', recipe.artProfile);
const result = await engine.call('export', { path: file, artProfile: recipe.artProfile, output: resolve('artifacts/smoke.tiff'), format: 'tiff' });
console.log('EXPORT', result);
await engine.stop();
